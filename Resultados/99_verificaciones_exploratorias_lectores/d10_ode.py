import numpy as np
from scipy.integrate import solve_ivp
k=dict(k1=0.003,km1=0.06,k2=0.01,km2=0.1,k3=1,km3=0.01,V4=450,K4=50,k5=0.06,km5=0.2,k6=1,km6=0.05,
 k7=0.3,km7=0.006,V8=1,K8=100,k9=1,km9=0.03,k10=0.214,km10=5.25,V11=4,K11=64,V12=3.5,K12=317,
 V13=0.058,K13=2200,V14=2.9,K14=317,V15=0.058,K15=60,V16=9.5,K16=1.46e5,V17=0.3,K17=160,V18=16,K18=1.46e5,V19=0.27,K19=60)
def rhs(t,X,p=k):
    X=np.concatenate([[0],X])
    v=[0]*20
    v[1]=p['k1']*X[1]*X[2]-p['km1']*X[3]
    v[2]=p['k2']*X[3]*X[3]-p['km2']*X[4]
    v[3]=p['k3']*X[4]-p['km3']*X[5]
    v[4]=p['V4']*X[5]/(p['K4']+X[5])
    v[5]=p['k5']*X[5]*X[6]-p['km5']*X[7]
    v[6]=p['k6']*X[7]-p['km6']*X[8]
    v[7]=p['k7']*X[8]-p['km7']*X[5]*X[9]
    v[8]=p['V8']*X[9]/(p['K8']+X[9])
    v[9]=p['k9']*X[9]-p['km9']*X[10]
    v[10]=p['k10']*X[9]*X[11]-p['km10']*X[12]
    v[11]=p['V11']*X[12]*X[13]/(p['K11']+X[13])
    v[12]=p['V12']*X[14]*X[15]/(p['K12']*(1+X[16]/p['K14'])+X[15])
    v[13]=p['V13']*X[16]/(p['K13']*(1+X[17]/p['K15'])+X[16])
    v[14]=p['V14']*X[14]*X[16]/(p['K14']*(1+X[15]/p['K12'])+X[16])
    v[15]=p['V15']*X[17]/(p['K15']*(1+X[16]/p['K13'])+X[17])
    v[16]=p['V16']*X[17]*X[18]/(p['K16']*(1+X[19]/p['K18'])+X[18])
    v[17]=p['V17']*X[19]/(p['K17']*(1+X[20]/p['K19'])+X[19])
    v[18]=p['V18']*X[17]*X[19]/(p['K18']*(1+X[18]/p['K16'])+X[19])
    v[19]=p['V19']*X[20]/(p['K19']*(1+X[19]/p['K17'])+X[20])
    d=[-v[1],-v[1],v[1]-2*v[2],v[2]+v[4]-v[3],v[3]+v[7]-v[4]-v[5],v[8]-v[5],v[5]-v[6],v[6]-v[7],
       v[7]-v[8]-v[9]-v[10],v[9],-v[10],v[10]-v[11],-v[11],v[11]-v[12]-v[14],v[13]-v[12],
       v[12]+v[15]-v[13]-v[14],v[14]-v[15]-v[16]-v[18],v[17]-v[16],v[16]+v[19]-v[17]-v[18],v[18]-v[19]]
    return d
for egf,egfr in [(2.56,80),(2.65*31.2,80),(2.65*50,80),(2.65*6,800)]:
    X0=[egf,egfr,0,0,0,10,0,0,0,0,10,0,100,0,120,0,0,100,0,0]
    sol=solve_ivp(rhs,(0,3000),X0,method='LSODA',t_eval=np.linspace(0,3000,3001),rtol=1e-8,atol=1e-10)
    X=sol.y; t=sol.t
    dplc=-np.gradient(X[5],t); derk=-np.gradient(X[17],t)
    i=np.argmax(dplc)
    print(f"EGF={egf:.2f} EGFR={egfr}: min conc={X.min():.2e}; PLCg(t=3000)={X[5,-1]:.3f}; max(-dPLC/dt)={dplc[i]:.3f} at t={t[i]:.0f}s; ERK-PP max={X[19].max():.4f}; max(-dERK/dt)={derk.max():.2e}; MEKtot end={X[14:17,-1].sum():.2f}")
